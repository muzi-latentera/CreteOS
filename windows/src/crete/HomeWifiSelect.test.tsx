import { act } from "react";
import { createRoot, type Root } from "react-dom/client";
import { afterEach, expect, it, vi } from "vitest";
import { invoke } from "@tauri-apps/api/core";
import { HomeWifiSelect } from "./HomeWifiSelect";
vi.mock("@tauri-apps/api/core", () => ({ invoke: vi.fn() }));
let root: Root;
let host: HTMLDivElement;
afterEach(async () => { await act(async () => root?.unmount()); host?.remove(); vi.clearAllMocks(); });
it("loads the provider preference and saves an explicit choice to that service", async () => {
  vi.mocked(invoke).mockResolvedValue({ moonlight: "automatic", geforceNow: "current", luna: "gaming" });
  host = document.createElement("div"); document.body.append(host); root = createRoot(host);
  const saving = vi.fn();
  await act(async () => root.render(<HomeWifiSelect provider="geforceNow" saving={saving} />));
  const select = host.querySelector("select")!;
  expect(select.value).toBe("current");
  expect(select.options[0].text).toContain("Fibre E433");
  await act(async () => { select.value = "download"; select.dispatchEvent(new Event("change", { bubbles: true })); });
  expect(invoke).toHaveBeenCalledWith("set_stream_wifi_preference", { provider: "geforceNow", choice: "download" });
  expect(select.value).toBe("download");
  expect(saving.mock.calls).toEqual([[true], [false]]);
});
it("retains the saved choice when a write fails", async () => {
  vi.mocked(invoke).mockImplementation(async command=>{if(command==="get_stream_network_status")return {wired:false};if(command==="get_stream_wifi_preferences")return {moonlight:"gaming"};throw "disk unavailable";});
  host = document.createElement("div"); root = createRoot(host);
  await act(async () => root.render(<HomeWifiSelect provider="moonlight" saving={() => {}} />));
  const select = host.querySelector("select")!;
  await act(async () => { select.value = "current"; select.dispatchEvent(new Event("change", { bubbles: true })); });
  expect(select.value).toBe("gaming");
  expect(host.querySelector('[role="alert"]')?.textContent).toContain("disk unavailable");
});
it("shows Ethernet and preserves the saved Wi-Fi fallback without saving on detection",async()=>{
  vi.mocked(invoke).mockImplementation(async command=>command==="get_stream_network_status"?{wired:true}:{moonlight:"gaming"});
  host=document.createElement("div");root=createRoot(host);
  await act(async()=>root.render(<HomeWifiSelect provider="moonlight" saving={()=>{}}/>));
  expect(host.textContent).toContain("Ethernet connected");
  expect(host.querySelector("select")!.value).toBe("gaming");
  expect(host.querySelector("select")!.options[0].text).toContain("Ethernet first");
  expect(invoke).not.toHaveBeenCalledWith("set_stream_wifi_preference",expect.anything());
});
it("previews the automatic Bosgame route and saves a separate override", async () => {
  vi.mocked(invoke).mockImplementation(async command => command === "get_stream_wifi_preferences" ? { moonlight: "gaming" } : { wired: false });
  host = document.createElement("div"); document.body.append(host); root = createRoot(host);
  await act(async () => root.render(<HomeWifiSelect provider="moonlight" host="Bosgame" saving={() => {}} />));
  const local = host.querySelector<HTMLSelectElement>('select[aria-label="G1 connection"]')!;
  const remote = host.querySelector<HTMLSelectElement>('select[aria-label="Bosgame connection"]')!;
  expect(remote.options[0].text).toBe("Automatic · Ethernet");
  await act(async () => { local.value = "download"; local.dispatchEvent(new Event("change", { bubbles: true })); });
  expect(remote.options[0].text).toBe("Automatic · Ethernet");
  await act(async () => { remote.value = "ethernet"; remote.dispatchEvent(new Event("change", { bubbles: true })); });
  expect(invoke).toHaveBeenCalledWith("set_bosgame_connection_preference", { choice: "ethernet" });
  expect(local.value).toBe("download");
  expect(remote.value).toBe("ethernet");
});
it("defaults to E433 only when Moonlight detects the dock", async () => {
  vi.mocked(invoke).mockImplementation(async command => command === "get_stream_network_status" ? { docked: true } : { moonlight: "automatic", bosgameConnection: "automatic" });
  host = document.createElement("div"); root = createRoot(host);
  await act(async () => root.render(<HomeWifiSelect provider="moonlight" host="Bosgame" saving={() => {}} />));
  const local = host.querySelector<HTMLSelectElement>('select[aria-label="G1 connection"]')!;
  expect(local.options[0].text).toContain("Fibre E433");
  expect(local.value).toBe("automatic");
});
